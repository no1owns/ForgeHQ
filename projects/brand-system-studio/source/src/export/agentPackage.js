import { exportAllThemeTokens } from './dtcgExport.js';
import { buildThemedCSS } from './cssExport.js';
import { generateDesignDoc } from './designDoc.js';
import { createZip } from './zip.js';

function generateAgentReadme(manifest) {
  return `# ${manifest.name} — agent package

Generated by Brand System Studio on ${manifest.generatedAt}.

## What's in here

- **tokens.json** — the default theme's (\`${manifest.defaultTheme}\`) canonical design tokens, in the [Design Tokens Community Group format](https://www.designtokens.org/) (targeting the 2025.10 draft — see the caveat below).
${manifest.extraThemeFiles.map((f) => `- **${f.file}** — the same system's \`${f.theme}\` theme tokens, same format.`).join('\n')}
- **tokens.css** — CSS custom properties generated from the token files above. Alias relationships are preserved as \`var()\` references, not flattened to literals, so changing one variable still cascades the way the tokens do. Opt into the ${manifest.themes.filter((t) => t !== manifest.defaultTheme).join('/')} theme by setting \`data-theme="..."\` on \`<html>\` or any ancestor.
- **DESIGN.md** — this system's intent and usage guidance, generated from the live tokens so it can't drift out of sync with them.
- **manifest.json** — this package's own structure (file paths, available themes, default theme), machine-readable.

## How to consume this

1. Read **manifest.json** first to find the right file for what you need.
2. For styling with plain CSS: use **tokens.css**.
3. For anything else (a design tool import, a different CSS-in-JS system, a build-time token pipeline): parse **tokens.json** (and the per-theme files) directly as DTCG tokens.
4. Read **DESIGN.md** before styling anything — it tells you which *semantic* token to reach for (e.g. \`semantic.color.action.primary\`), which is almost always what you want instead of a raw primitive color.
5. If nothing in here covers what you're trying to style, don't invent a value — DESIGN.md explains how to propose a new token instead.

## Limitations

- **Spec fidelity**: this package targets the DTCG Format Module, version 2025.10. The tool that generated it could not fetch and verify against the live spec text in its environment (a network restriction, not a design choice) — the token shapes, especially the structured \`color\` \$value, reflect best-effort trained knowledge of the format, not a freshly-verified read. Validate against the actual spec if correctness here matters for your use case.
- **Compatibility is not claimed, only described**: this package has not been tested against Figma's variable import, Tokens Studio, Style Dictionary, or any other specific tool. Treat it as "DTCG export, compatibility not yet verified" for all of them until you've actually tried the round trip.
- **Not everything is a token**: responsive/breakpoint behavior isn't represented here (DTCG has no token type for it) — see DESIGN.md's Responsive behavior section instead.
- **The accessibility note in DESIGN.md is a single contrast-ratio check**, not a full audit.
`;
}

/** The default theme's name goes into tokens.json unprefixed; every
 * OTHER theme gets its own tokens.<theme>.json — "additional theme token
 * files when present", not a duplicate of the default theme. */
export function buildAgentPackage(system, { name = 'brand-system', defaultTheme = 'light' } = {}) {
  const themeTokens = exportAllThemeTokens(system);
  const themes = Object.keys(themeTokens);
  const extraThemes = themes.filter((t) => t !== defaultTheme);
  const extraThemeFiles = extraThemes.map((t) => ({ theme: t, file: `tokens.${t}.json` }));

  const css = buildThemedCSS(system);
  const design = generateDesignDoc(system, { themes });

  const manifest = {
    schemaVersion: 1,
    name,
    generatedAt: new Date().toISOString(),
    defaultTheme,
    themes,
    files: {
      tokens: 'tokens.json',
      extraThemeTokens: Object.fromEntries(extraThemeFiles.map((f) => [f.theme, f.file])),
      css: 'tokens.css',
      design: 'DESIGN.md',
      readme: 'README.md',
    },
    extraThemeFiles,
  };

  const files = [
    { name: 'tokens.json', content: JSON.stringify(themeTokens[defaultTheme], null, 2) },
    ...extraThemeFiles.map((f) => ({ name: f.file, content: JSON.stringify(themeTokens[f.theme], null, 2) })),
    { name: 'tokens.css', content: css },
    { name: 'DESIGN.md', content: design },
    { name: 'manifest.json', content: JSON.stringify(manifest, null, 2) },
    { name: 'README.md', content: generateAgentReadme(manifest) },
  ];

  return { files, manifest };
}

export function buildAgentZip(system, opts) {
  const { files, manifest } = buildAgentPackage(system, opts);
  return { bytes: createZip(files), manifest };
}
