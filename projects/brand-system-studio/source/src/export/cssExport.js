import { flattenSystem } from '../tokens/project.js';
import { toCSSVariables, toCompositeCSSVariables } from '../tokens/serialize.js';

/**
 * CSS custom properties for a whole system, both themes. Primitive and
 * component values are theme-independent (only *which* primitive a
 * semantic role points to changes between themes — see tokens/defaults.js)
 * so they're emitted once under :root; semantic values are emitted twice,
 * once for light (the default, so it also matches plain :root with no
 * data-theme attribute) and once for [data-theme="dark"] — a documented,
 * predictable selector convention a consuming site opts into by setting
 * that attribute (e.g. on <html>).
 */
export function buildThemedCSS(system) {
  const lightFlat = flattenSystem(system, 'light');
  const darkFlat = flattenSystem(system, 'dark');
  const shared = new Map([...lightFlat].filter(([p]) => !p.startsWith('semantic.')));
  const lightSemantic = new Map([...lightFlat].filter(([p]) => p.startsWith('semantic.')));
  const darkSemantic = new Map([...darkFlat].filter(([p]) => p.startsWith('semantic.')));

  const header = '/* Generated by Brand System Studio.\n' +
    '   Primitive and component values are theme-independent; only which\n' +
    '   primitive a semantic role points to changes between themes. Opt into\n' +
    '   dark mode by setting data-theme="dark" on <html> (or any ancestor). */\n\n';

  return (
    header +
    toCSSVariables(shared, { selector: ':root' }) +
    toCompositeCSSVariables(shared, { selector: ':root' }) +
    '\n' +
    toCSSVariables(lightSemantic, { selector: ':root, [data-theme="light"]' }) +
    toCompositeCSSVariables(lightSemantic, { selector: ':root, [data-theme="light"]' }) +
    '\n' +
    toCSSVariables(darkSemantic, { selector: '[data-theme="dark"]' }) +
    toCompositeCSSVariables(darkSemantic, { selector: '[data-theme="dark"]' })
  );
}
